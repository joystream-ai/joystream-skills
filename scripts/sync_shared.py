#!/usr/bin/env python3
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Copy the shared contracts in schemas/ into every skill and template, or check that they match.

A skill may only reference files inside its own directory (Agent Skills spec; JoyStream
captures one skill directory per bundle), so shared material is copied, not linked:

- schemas/report.schema.json       -> properties.report of each skill's assets/output.schema.json
- schemas/item-result.schema.json  -> properties.item_result of the same file
- schemas/state.schema.json        -> properties.state_out of the same file
                                      (each only where that property already exists)
- schemas/source-shapes.md    -> the block between the source-shapes markers in SKILL.md
                                 (only where the markers already exist)

    uv run scripts/sync_shared.py            # rewrite drifted copies
    uv run scripts/sync_shared.py --check    # exit 1 on drift, change nothing
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL_ROOTS = (ROOT / "skills", ROOT / "templates")
# Output-schema property -> the shared schema copied into it.
SHARED_PROPERTIES = {
    "report": ROOT / "schemas" / "report.schema.json",
    "item_result": ROOT / "schemas" / "item-result.schema.json",
    "state_out": ROOT / "schemas" / "state.schema.json",
}
SOURCE_SHAPES = ROOT / "schemas" / "source-shapes.md"

START_MARKER = "<!-- shared:source-shapes (generated by scripts/sync_shared.py; edit schemas/source-shapes.md) -->"
END_MARKER = "<!-- /shared:source-shapes -->"

# Keywords that only make sense at a schema's root; an embedded copy must drop them.
_ROOT_ONLY_KEYS = ("$schema", "$id")


def embedded_schema(path: Path) -> dict:
    schema = json.loads(path.read_text())
    for key in _ROOT_ONLY_KEYS:
        schema.pop(key, None)
    return schema


def dump_json(value: dict) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def sync_output_schema(path: Path, shared: dict[str, dict], check: bool) -> bool:
    """Return True when the file is (or was) out of date."""
    schema = json.loads(path.read_text())
    props = schema.get("properties")
    if not isinstance(props, dict):
        return False
    stale = [name for name, wanted in shared.items() if name in props and props[name] != wanted]
    if not stale:
        return False
    if not check:
        for name in stale:
            props[name] = shared[name]
        path.write_text(dump_json(schema))
    return True


def sync_skill_body(path: Path, block: str, check: bool) -> bool:
    text = path.read_text()
    start = text.find(START_MARKER)
    if start == -1:
        return False
    end = text.find(END_MARKER, start)
    if end == -1:
        raise ValueError(f"{path}: start marker without end marker")
    current = text[start + len(START_MARKER) : end]
    wanted = "\n" + block.strip("\n") + "\n"
    if current == wanted:
        return False
    if not check:
        path.write_text(text[: start + len(START_MARKER)] + wanted + text[end:])
    return True


def run(check: bool, skill_roots: tuple[Path, ...] = SKILL_ROOTS, repo_root: Path = ROOT) -> list[str]:
    shared = {name: embedded_schema(path) for name, path in SHARED_PROPERTIES.items()}
    block = SOURCE_SHAPES.read_text()
    drifted: list[str] = []
    skill_dirs = sorted(p for r in skill_roots if r.is_dir() for p in r.iterdir() if p.is_dir())
    for skill_dir in skill_dirs:
        output_schema = skill_dir / "assets" / "output.schema.json"
        if output_schema.is_file() and sync_output_schema(output_schema, shared, check):
            drifted.append(str(output_schema.relative_to(repo_root)))
        skill_md = skill_dir / "SKILL.md"
        if skill_md.is_file() and sync_skill_body(skill_md, block, check):
            drifted.append(str(skill_md.relative_to(repo_root)))
    return drifted


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift and exit 1; change nothing")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    args = parser.parse_args()

    drifted = run(check=args.check)
    if args.json:
        print(json.dumps({"check": args.check, "drifted": drifted}))
    elif drifted:
        verb = "out of date" if args.check else "updated"
        print(f"{len(drifted)} file(s) {verb}:")
        for path in drifted:
            print(f"  {path}")
    else:
        print("shared copies are in sync")
    return 1 if (args.check and drifted) else 0


if __name__ == "__main__":
    sys.exit(main())
