#!/usr/bin/env python3
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyyaml>=6"]
# ///
"""Generate the README skills table from each skill's frontmatter, or check that it is current.

The table between the skills-table markers in README.md is rebuilt from every
skills/*/SKILL.md (frontmatter `name`, `description`, `metadata.version`,
`metadata.category`) and the .claude-plugin/marketplace.json entry that lists the skill,
one row per skill, sorted by name. Everything outside the markers is left alone.

    uv run scripts/readme_table.py            # rewrite the table
    uv run scripts/readme_table.py --check    # exit 1 when the table is out of date, change nothing
    uv run scripts/readme_table.py --json     # print {"changed": bool, "skills": int}
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- skills-table:start -->"
END = "<!-- skills-table:end -->"
NOTE = "<!-- generated by scripts/readme_table.py from each SKILL.md frontmatter; do not edit by hand -->"
HEADER = (
    "| Skill (`name`) | What it does | Version | Category | Plugin |",
    "|----------------|--------------|---------|----------|--------|",
)
MISSING = "—"


class TableError(Exception):
    """The README or a skill cannot be read well enough to build the table."""


def frontmatter(skill_md: Path) -> dict:
    text = skill_md.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise TableError(f"{skill_md}: no YAML frontmatter")
    end = text.find("\n---", 4)
    if end == -1:
        raise TableError(f"{skill_md}: frontmatter is not closed with ---")
    try:
        data = yaml.safe_load(text[4:end])
    except yaml.YAMLError as exc:
        raise TableError(f"{skill_md}: frontmatter is not valid YAML: {exc}") from exc
    if not isinstance(data, dict):
        raise TableError(f"{skill_md}: frontmatter is not a mapping")
    return data


def plugin_owners(root: Path) -> dict[Path, list[str]]:
    """Resolved skill directory -> names of the marketplace entries that list it."""
    manifest = root / ".claude-plugin" / "marketplace.json"
    if not manifest.is_file():
        return {}
    owners: dict[Path, list[str]] = {}
    for entry in json.loads(manifest.read_text(encoding="utf-8")).get("plugins", []):
        source = root / entry.get("source", "./")
        for rel in entry.get("skills", []):
            owners.setdefault((source / rel).resolve(), []).append(entry.get("name", "?"))
    return owners


def cell(value: object) -> str:
    """One Markdown table cell: a single line, pipes escaped."""
    if value is None or value == "":
        return MISSING
    return re.sub(r"\s+", " ", str(value)).strip().replace("|", "\\|")


def rows(root: Path) -> list[str]:
    skills_dir = root / "skills"
    skill_mds = sorted(skills_dir.glob("*/SKILL.md")) if skills_dir.is_dir() else []
    owners = plugin_owners(root)
    entries = []
    for skill_md in skill_mds:
        data = frontmatter(skill_md)
        metadata = data.get("metadata") if isinstance(data.get("metadata"), dict) else {}
        folder = skill_md.parent.name
        name = str(data.get("name") or folder)
        plugins = owners.get(skill_md.parent.resolve(), [])
        entries.append((name, (
            f"[`{name}`](./skills/{folder}/SKILL.md)",
            cell(data.get("description")),
            cell(metadata.get("version")),
            cell(metadata.get("category")),
            ", ".join(f"`{p}`" for p in plugins) if plugins else MISSING,
        )))
    entries.sort(key=lambda e: e[0])
    return ["| " + " | ".join(columns) + " |" for _, columns in entries]


def render(root: Path) -> tuple[str, int]:
    body = rows(root)
    return "\n".join((NOTE, *HEADER, *body)), len(body)


def run(root: Path, check: bool) -> dict:
    """Rebuild the table in <root>/README.md (or only compare, with check=True)."""
    readme = root / "README.md"
    if not readme.is_file():
        raise TableError(f"{readme} not found")
    text = readme.read_text(encoding="utf-8")
    start, end = text.find(START), text.find(END)
    if start == -1 or end == -1 or end < start:
        raise TableError(f"{readme} needs the markers {START} and {END}, in that order, around the skills table")
    table, count = render(root)
    updated = text[: start + len(START)] + "\n" + table + "\n" + text[end:]
    changed = updated != text
    if changed and not check:
        readme.write_text(updated, encoding="utf-8")
    return {"changed": changed, "skills": count}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=str(ROOT), help="repo root (default: this script's repo)")
    parser.add_argument("--check", action="store_true", help="exit 1 when the table is out of date; change nothing")
    parser.add_argument("--json", action="store_true", help="print the result as JSON")
    args = parser.parse_args()

    try:
        result = run(Path(args.root), check=args.check)
    except TableError as exc:
        print(f"readme_table: {exc}", file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(result))
    elif args.check and result["changed"]:
        print(f"README skills table is out of date ({result['skills']} skills); run: uv run scripts/readme_table.py")
    else:
        state = "updated" if result["changed"] else "up to date"
        print(f"README skills table {state} ({result['skills']} skills)")
    return 1 if args.check and result["changed"] else 0


if __name__ == "__main__":
    sys.exit(main())
